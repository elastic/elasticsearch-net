namespace RequestConverter;

/// <summary>
/// Controls how <see cref="CodeWriter"/> renders generated C# code.
/// </summary>
public sealed record FormattingOptions
{
	/// <summary>The default options: four-space indentation, <c>\n</c> line endings, object-initializer syntax.</summary>
	public static FormattingOptions Default { get; } = new();

	/// <summary>The string used for a single level of indentation. Defaults to four spaces.</summary>
	public string IndentString { get; init; } = "    ";

	/// <summary>The line ending appended by <see cref="CodeWriter.WriteLine(string)"/>. Defaults to <c>\n</c>.</summary>
	public string NewLine { get; init; } = "\n";

	/// <summary>Which C# syntax flavor to emit. Defaults to <see cref="SyntaxMode.ObjectInitializer"/>.</summary>
	public SyntaxMode SyntaxMode { get; init; } = SyntaxMode.ObjectInitializer;

	/// <summary>How object initializers name their constructor. Defaults to target-typed <c>new()</c>.</summary>
	public ConstructorStyle ConstructorStyle { get; init; } = ConstructorStyle.TargetTyped;

	/// <summary>
	/// When <c>true</c>, the emitted code is a variable declaration statement (<c>SearchRequest request = new() { ... };</c>)
	/// rather than the bare initializer expression. The declared type names the target request, so its namespace is
	/// reported and a target-typed <c>new()</c> resolves against it. Defaults to <c>false</c>.
	/// </summary>
	public bool EmitVariableDeclaration { get; init; }

	/// <summary>The variable name used when <see cref="EmitVariableDeclaration"/> is set. Defaults to <c>request</c>.</summary>
	public string VariableName { get; init; } = "request";

	/// <summary>How type names are rendered. Defaults to <see cref="TypeNameStyle.Simplified"/> (short identifiers,
	/// relying on the using directives the caller adds from the returned namespaces).</summary>
	public TypeNameStyle TypeNameStyle { get; init; } = TypeNameStyle.Simplified;

	/// <summary>
	/// When <c>true</c>, field references emit <c>Infer.Field&lt;<see cref="DocumentTypeName"/>&gt;(x =&gt; x.Path)</c>
	/// lambdas (likewise <c>Infer.Fields</c>/<c>Infer.Property</c>) and a generic request's document body emits
	/// <c>new <see cref="DocumentTypeName"/> { ... }</c>. The named type is not generated by the converter; the caller
	/// supplies it, so the output is illustrative and generally does not compile or round-trip as-is. When <c>false</c>
	/// (the default), fields render as string literals and document bodies as <c>JsonElement</c>.
	/// </summary>
	public bool UseStronglyTypedDocument { get; init; }

	/// <summary>The placeholder document type name used when <see cref="UseStronglyTypedDocument"/> is set. Defaults to <c>MyDocument</c>.</summary>
	public string DocumentTypeName { get; init; } = "MyDocument";

	/// <summary>
	/// How the client invocation that executes the request is emitted. Defaults to
	/// <see cref="ClientCallFormat.None"/> (no invocation; the output is the bare request/descriptor expression).
	/// </summary>
	public ClientCallFormat ClientCallFormat { get; init; } = ClientCallFormat.None;

	/// <summary>The invocation flavor used when <see cref="ClientCallFormat"/> is not <see cref="ClientCallFormat.None"/>. Defaults to <see cref="ClientCallStyle.Async"/>.</summary>
	public ClientCallStyle ClientCallStyle { get; init; } = ClientCallStyle.Async;

	/// <summary>The client variable name used when <see cref="ClientCallFormat"/> is not <see cref="ClientCallFormat.None"/>. Defaults to <c>client</c>.</summary>
	public string ClientVariableName { get; init; } = "client";

	/// <summary>The response variable name used when <see cref="ClientCallFormat"/> is not <see cref="ClientCallFormat.None"/>. Defaults to <c>response</c>.</summary>
	public string ResponseVariableName { get; init; } = "response";
}

/// <summary>
/// Controls how <see cref="CodeWriter"/> spells type names. The accompanying set of referenced namespaces is reported
/// regardless of the style, so a caller using <see cref="Simplified"/> can add the matching <c>using</c> directives.
/// </summary>
public enum TypeNameStyle
{
	/// <summary>
	/// Short identifiers (e.g. <c>Dictionary&lt;string, Aggregation&gt;</c>), assuming the referenced namespaces are
	/// imported. A name that is ambiguous against the imported set falls back to its <see cref="GlobalFqn"/> form so the
	/// output always compiles.
	/// </summary>
	Simplified = 0,

	/// <summary>Fully-qualified names without the <c>global::</c> prefix (e.g. <c>System.Collections.Generic.Dictionary&lt;...&gt;</c>).</summary>
	Fqn = 1,

	/// <summary>Fully-qualified names with the <c>global::</c> prefix (e.g. <c>global::System.Collections.Generic.Dictionary&lt;...&gt;</c>).</summary>
	GlobalFqn = 2
}

/// <summary>
/// The invocation flavor emitted for the client call (see <see cref="FormattingOptions.ClientCallFormat"/>).
/// </summary>
public enum ClientCallStyle
{
	/// <summary>The awaited asynchronous method, e.g. <c>var response = await client.SearchAsync&lt;JsonElement&gt;(request);</c>.</summary>
	Async = 0,

	/// <summary>The synchronous method, e.g. <c>var response = client.Search&lt;JsonElement&gt;(request);</c>.</summary>
	Sync = 1
}

/// <summary>
/// How the client invocation that executes a converted request is emitted (see
/// <see cref="FormattingOptions.ClientCallFormat"/>).
/// </summary>
public enum ClientCallFormat
{
	/// <summary>No client invocation; the output is the bare request/descriptor expression.</summary>
	None = 0,

	/// <summary>A variable declaration followed by a call statement referencing it, e.g.
	/// <c>SearchRequest request = new() { ... };</c> then
	/// <c>var response = await client.SearchAsync&lt;JsonElement&gt;(request);</c>. Implies
	/// <see cref="FormattingOptions.EmitVariableDeclaration"/>.</summary>
	Statement = 1,

	/// <summary>The request initializer (object-initializer mode) or descriptor lambda (descriptor mode) is
	/// inlined as the call argument, e.g.
	/// <c>var response = await client.SearchAsync&lt;JsonElement&gt;(s =&gt; s.Query(...));</c>.
	/// <see cref="FormattingOptions.EmitVariableDeclaration"/> is ignored.</summary>
	Inline = 2
}

/// <summary>
/// Controls how <see cref="CodeWriter.BeginObjectInitializer(string)"/> renders the constructor.
/// </summary>
public enum ConstructorStyle
{
	/// <summary>Target-typed, e.g. <c>new() { ... }</c> (relies on the assignment target's type).</summary>
	TargetTyped = 0,

	/// <summary>Explicit, e.g. <c>new SearchRequest() { ... }</c> (self-contained, given the right usings).</summary>
	Explicit = 1
}

/// <summary>
/// The C# syntax flavor emitted by the request converter.
/// </summary>
public enum SyntaxMode
{
	/// <summary>Object-initializer syntax, e.g. <c>new() { Prop = value }</c>.</summary>
	ObjectInitializer = 0,

	/// <summary>
	/// Descriptor (fluent lambda) syntax, e.g. <c>new SearchRequestDescriptor&lt;T&gt;().Query(q =&gt; q.Match(m =&gt; ...))</c>.
	/// Pairs with <see cref="FormattingOptions.UseStronglyTypedDocument"/>: when set, emits the generic
	/// <c>XDescriptor&lt;DocumentTypeName&gt;</c> flavor with <c>.Field(f =&gt; f.Path)</c> expression lambdas; otherwise the
	/// non-generic descriptor with string field values.
	/// </summary>
	Descriptor = 1,
}
